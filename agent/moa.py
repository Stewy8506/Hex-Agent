"""Mixture-of-Agents (MoA) Proposer-Aggregator Multi-Model Synthesis Engine.

Coordinates concurrent reasoning queries across diverse proposer models,
gathers candidate solutions, and synthesizes authoritative responses through
a primary aggregator model with error tolerance, token accounting, and fallback.
"""

from __future__ import annotations

from concurrent.futures import ThreadPoolExecutor, TimeoutError as FuturesTimeoutError
from dataclasses import dataclass, field
import inspect
import logging
import time
from typing import Any, Callable

logger = logging.getLogger(__name__)


@dataclass
class ProposerConfig:
    """Configuration for an individual candidate proposer or aggregator model."""

    model: str
    temperature: float = 0.7
    provider: str | None = None
    timeout_seconds: float = 15.0
    max_tokens: int | None = None


@dataclass
class MoAConfig:
    """Configuration for the Mixture-of-Agents orchestration engine."""

    proposers: list[ProposerConfig] = field(default_factory=list)
    aggregator: ProposerConfig | None = None
    min_proposers_required: int = 1
    max_parallel_workers: int = 4
    enabled: bool = True
    timeout_seconds: float = 30.0


@dataclass
class ProposerOutput:
    """Output generated by a single candidate proposer model."""

    candidate_index: int
    model: str
    content: str
    latency_ms: float = 0.0
    tokens_used: int = 0
    is_error: bool = False
    error_message: str | None = None


@dataclass
class MoAResult:
    """Synthesized result produced by the Mixture-of-Agents pipeline."""

    synthesized_text: str
    proposer_outputs: list[ProposerOutput] = field(default_factory=list)
    total_latency_ms: float = 0.0
    aggregator_model: str = ""
    total_tokens: int = 0
    fallback_used: bool = False

    def __getitem__(self, key: Any) -> Any:
        if not hasattr(self, str(key)):
            raise KeyError(key)
        return getattr(self, str(key))

    def __contains__(self, key: Any) -> bool:
        return hasattr(self, str(key))

    def get(self, key: str, default: Any = None) -> Any:
        return getattr(self, key, default)

    def to_dict(self) -> dict[str, Any]:
        """Convert MoAResult to a serializable dictionary."""
        return {
            "synthesized_text": self.synthesized_text,
            "proposer_outputs": [
                {
                    "candidate_index": p.candidate_index,
                    "model": p.model,
                    "content": p.content,
                    "latency_ms": p.latency_ms,
                    "tokens_used": p.tokens_used,
                    "is_error": p.is_error,
                    "error_message": p.error_message,
                }
                for p in self.proposer_outputs
            ],
            "total_latency_ms": self.total_latency_ms,
            "aggregator_model": self.aggregator_model,
            "total_tokens": self.total_tokens,
            "fallback_used": self.fallback_used,
        }


class MixtureOfAgents:
    """Orchestrates multi-model proposer queries and aggregator synthesis."""

    def __init__(
        self,
        config: MoAConfig,
        model_caller: Callable[..., Any] | None = None,
        router: Any = None,
    ) -> None:
        self.config = config
        self.model_caller = model_caller
        self.router = router
        if self.config.aggregator is None:
            self.config.aggregator = ProposerConfig(
                model="primary-aggregator",
                temperature=0.2,
            )

    def _extract_text_and_tokens(self, response: Any) -> tuple[str, int]:
        """Extract plain text and token count from diverse model response types."""
        if isinstance(response, str):
            text = response
            tokens = max(1, len(text) // 4)
            return text, tokens

        text = ""
        tokens = 0

        if hasattr(response, "text") and isinstance(response.text, str):
            text = response.text
        elif hasattr(response, "content") and isinstance(response.content, str):
            text = response.content
        elif isinstance(response, dict):
            text = str(response.get("text") or response.get("content") or "")
        else:
            text = str(response)

        if hasattr(response, "usage") and response.usage is not None:
            tokens = getattr(response.usage, "total_tokens", 0) or (
                getattr(response.usage, "prompt_tokens", 0)
                + getattr(response.usage, "completion_tokens", 0)
            )
        elif isinstance(response, dict) and "usage" in response:
            u = response["usage"]
            if isinstance(u, dict):
                tokens = u.get("total_tokens", 0) or (
                    u.get("prompt_tokens", 0) + u.get("completion_tokens", 0)
                )

        if tokens == 0 and text:
            tokens = max(1, len(text) // 4)

        return text, tokens

    def _call_candidate(
        self,
        candidate_idx: int,
        proposer: ProposerConfig,
        prompt: str,
        messages: list[dict[str, Any]],
    ) -> ProposerOutput:
        """Execute a single model invocation with timing and error isolation."""
        t_start = time.perf_counter()
        try:
            resp: Any = None
            if self.model_caller is not None:
                # Try calling with messages and proposer configuration
                called = False
                sig = None
                try:
                    sig = inspect.signature(self.model_caller)
                except (ValueError, TypeError):
                    pass

                if sig is not None:
                    param_count = len(sig.parameters)
                    if param_count >= 2:
                        try:
                            resp = self.model_caller(messages, proposer)
                            called = True
                        except TypeError:
                            pass
                    elif param_count == 1:
                        try:
                            resp = self.model_caller(messages)
                            called = True
                        except TypeError:
                            pass

                if not called:
                    try:
                        resp = self.model_caller(messages, proposer)
                    except TypeError:
                        try:
                            resp = self.model_caller(messages=messages, model=proposer.model)
                        except TypeError:
                            try:
                                resp = self.model_caller(messages)
                            except TypeError:
                                resp = self.model_caller(prompt)

            elif self.router is not None:
                if hasattr(self.router, "route"):
                    resp = self.router.route(prompt=prompt, messages=messages, model=proposer.model)
                elif hasattr(self.router, "generate"):
                    resp = self.router.generate(messages=messages, model=proposer.model)
                else:
                    raise RuntimeError("Configured router lacks route/generate method")
            else:
                raise RuntimeError("No model_caller or router configured for MixtureOfAgents")

            elapsed_ms = (time.perf_counter() - t_start) * 1000
            content, tokens = self._extract_text_and_tokens(resp)
            return ProposerOutput(
                candidate_index=candidate_idx,
                model=proposer.model,
                content=content,
                latency_ms=elapsed_ms,
                tokens_used=tokens,
                is_error=False,
            )
        except Exception as exc:
            elapsed_ms = (time.perf_counter() - t_start) * 1000
            logger.warning("Proposer %s (candidate %d) failed: %s", proposer.model, candidate_idx, exc)
            return ProposerOutput(
                candidate_index=candidate_idx,
                model=proposer.model,
                content="",
                latency_ms=elapsed_ms,
                tokens_used=0,
                is_error=True,
                error_message=str(exc),
            )

    def query_proposers(
        self,
        prompt: str,
        messages: list[dict[str, Any]] | None = None,
    ) -> list[ProposerOutput]:
        """Execute concurrent queries across all proposer models."""
        if not messages:
            messages = [{"role": "user", "content": prompt}]

        if not self.config.proposers:
            return []

        max_workers = min(
            len(self.config.proposers),
            max(1, self.config.max_parallel_workers),
        )

        outputs: list[ProposerOutput] = []
        with ThreadPoolExecutor(max_workers=max_workers) as executor:
            future_map = {
                executor.submit(
                    self._call_candidate, idx, proposer, prompt, messages
                ): (idx, proposer)
                for idx, proposer in enumerate(self.config.proposers)
            }

            for future, (idx, proposer) in future_map.items():
                try:
                    out = future.result(timeout=proposer.timeout_seconds)
                    outputs.append(out)
                except FuturesTimeoutError:
                    outputs.append(
                        ProposerOutput(
                            candidate_index=idx,
                            model=proposer.model,
                            content="",
                            latency_ms=proposer.timeout_seconds * 1000,
                            tokens_used=0,
                            is_error=True,
                            error_message=f"Timeout after {proposer.timeout_seconds}s",
                        )
                    )
                except Exception as exc:
                    outputs.append(
                        ProposerOutput(
                            candidate_index=idx,
                            model=proposer.model,
                            content="",
                            latency_ms=0.0,
                            tokens_used=0,
                            is_error=True,
                            error_message=str(exc),
                        )
                    )

        outputs.sort(key=lambda o: o.candidate_index)
        return outputs

    def build_aggregator_prompt(
        self,
        prompt: str,
        proposer_outputs: list[ProposerOutput],
    ) -> list[dict[str, Any]]:
        """Format candidate solutions into an authoritative synthesis prompt."""
        valid_candidates = [p for p in proposer_outputs if not p.is_error and p.content.strip()]
        system_instruction = (
            "You have been provided with responses from candidate reasoning models. "
            "Synthesize the most accurate, cohesive, and complete solution. "
            "Reconcile contradictions and eliminate errors."
        )

        if not valid_candidates:
            return [
                {"role": "system", "content": system_instruction},
                {"role": "user", "content": prompt},
            ]

        sections: list[str] = []
        for i, cand in enumerate(valid_candidates, start=1):
            sections.append(
                f"=== Candidate {i} (Model: {cand.model}) ===\n{cand.content.strip()}"
            )
        candidate_body = "\n\n".join(sections)

        user_content = (
            f"Original Objective:\n{prompt}\n\n"
            f"Candidate Model Responses:\n{candidate_body}\n\n"
            "Synthesize the most accurate, cohesive, and complete solution. "
            "Reconcile contradictions and eliminate errors."
        )

        return [
            {"role": "system", "content": system_instruction},
            {"role": "user", "content": user_content},
        ]

    def synthesize(
        self,
        prompt: str,
        messages: list[dict[str, Any]] | None = None,
    ) -> MoAResult:
        """Orchestrate proposer fan-out, filter results, and synthesize via primary aggregator."""
        t_start = time.perf_counter()
        if not messages:
            messages = [{"role": "user", "content": prompt}]

        aggregator = self.config.aggregator or ProposerConfig(model="primary-aggregator", temperature=0.2)

        # If no proposers are configured, invoke aggregator directly
        if not self.config.proposers:
            agg_out = self._call_candidate(0, aggregator, prompt, messages)
            total_latency = (time.perf_counter() - t_start) * 1000
            return MoAResult(
                synthesized_text=agg_out.content,
                proposer_outputs=[],
                total_latency_ms=total_latency,
                aggregator_model=aggregator.model,
                total_tokens=agg_out.tokens_used,
                fallback_used=False,
            )

        proposer_outputs = self.query_proposers(prompt, messages)
        successful_proposers = [p for p in proposer_outputs if not p.is_error and p.content.strip()]

        fallback_used = False
        if len(successful_proposers) < self.config.min_proposers_required:
            fallback_used = True
            logger.info(
                "MoA: Insufficient successful proposers (%d < %d required). Falling back directly to aggregator alone.",
                len(successful_proposers),
                self.config.min_proposers_required,
            )
            agg_out = self._call_candidate(0, aggregator, prompt, messages)
        else:
            aggregator_messages = self.build_aggregator_prompt(prompt, proposer_outputs)
            agg_out = self._call_candidate(0, aggregator, prompt, aggregator_messages)

        proposer_tokens = sum(p.tokens_used for p in proposer_outputs)
        total_tokens = proposer_tokens + agg_out.tokens_used
        total_latency = (time.perf_counter() - t_start) * 1000

        return MoAResult(
            synthesized_text=agg_out.content,
            proposer_outputs=proposer_outputs,
            total_latency_ms=total_latency,
            aggregator_model=aggregator.model,
            total_tokens=total_tokens,
            fallback_used=fallback_used,
        )
